-- Миграция: Создание таблицы базы знаний (статей)
create table if not exists public.articles (
    id bigint generated by default as identity not null,
    title character varying not null,
    content text not null,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint articles_pkey primary key (id)
) tablespace pg_default;

comment on table public.articles is 'Таблица базы знаний (статьи)';
comment on column public.articles.id is 'Уникальный числовой идентификатор статьи';
comment on column public.articles.title is 'Заголовок статьи (headline)';
comment on column public.articles.content is 'Содержимое/текст статьи';
comment on column public.articles.created_at is 'Дата и время создания статьи';
comment on column public.articles.updated_at is 'Дата и время последнего редактирования статьи';

create or replace function public.update_articles_updated_at()
returns trigger as $$
begin
    new.updated_at = now();
    return new;
end;
$$ language plpgsql;

drop trigger if exists trigger_update_articles_updated_at on public.articles;
create trigger trigger_update_articles_updated_at
    before update on public.articles
    for each row
    execute function public.update_articles_updated_at();

create index if not exists idx_articles_created_at on public.articles (created_at desc);
create index if not exists idx_articles_updated_at on public.articles (updated_at desc);
create index if not exists idx_articles_title on public.articles (title);
